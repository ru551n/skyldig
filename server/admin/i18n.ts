export type AdminMessages = typeof sv;

export function messages(locale: AdminLocale): AdminMessages {
  return locale === "en" ? en : sv;
}

/**
 * `?lang=` wins so the language links work without cookies; otherwise the most-preferred
 * Accept-Language tag, defaulting to Swedish. Self-contained on purpose: the admin process must not
 * pull in the main app's translation module or its config.
 */
export function resolveAdminLocale(langParam: unknown, acceptLanguage: string | undefined): AdminLocale {
  if (langParam === "sv" || langParam === "en") return langParam;
  const preferred = (acceptLanguage ?? "")
    .split(",")
    .map((part) => {
      const [tag = "", q] = part.trim().split(";q=");
      const weight = q ? Number.parseFloat(q) : 1;
      return { tag: tag.trim().toLowerCase(), weight: Number.isFinite(weight) ? weight : 1 };
    })
    .filter((entry) => entry.tag)
    .sort((a, b) => b.weight - a.weight)[0];
  return preferred?.tag.startsWith("en") ? "en" : "sv";
}
